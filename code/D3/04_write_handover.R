tier_of <- function(nA, nB, nC) {
  k <- nA + nB + nC
  if (k == 3) "T4_triple_notDEG" else if (k == 2) "T5_other" else "T5_other"
}
cand <- rbindlist(lapply(c("SERPINE1", "THBS1", "LOX"), function(g) {
  p_ <- pool[gene == g]
  f_ <- full2[gene == g]
  if (nrow(p_)) {
    data.table(gene = g, n_source_sets = p_$n_source_sets, n_theme = p_$n_theme,
               tier = p_$tier, logFC = p_$logFC, adjP = p_$adjP)
  } else {
    data.table(gene = g, n_source_sets = f_$n_source_sets,
               n_theme = as.integer(f_$in_theme_A + f_$in_theme_B + f_$in_theme_C),
               tier = tier_of(f_$in_theme_A, f_$in_theme_B, f_$in_theme_C),
               logFC = f_$logFC, adjP = f_$adjP)
  }
}))

