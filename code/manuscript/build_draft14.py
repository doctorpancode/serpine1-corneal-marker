# ================================================================ 5 结论
h("5 结论", 1)
para("这项工作的落点是相关与可扰动之间的落差，以及标志物与靶点之间的落差。被反复报道的促血管基因，"
     "大多没被追问过在网络上承担什么角色：是发出信号、传递信号，还是仅随炎症升高而被记录。本研究用两个"
     "独立人队列与一次全基因虚拟敲除把 SERPINE1 放到这两个问题上分别检验，得到方向相反的答案：它在单一平台、"
     "27 例的外部队列上复现了判别力（AUC 0.988，校准待前瞻队列），在网络上几乎不是节点（上皮核效应 "
     "5.9×10⁻⁴，为 TMSB4X 的 1/462，四种度量下排名均在后三分之一）。抗血管靶点与疾病标志物因此未必同类，"
     "按连接度排出的靶点优先级必须先扣掉连接度自身的贡献，而表达丰度是同一枚硬币的另一面（ρ = 0.486）：扣除两者之后 TMSB4X 仍居首，但与次位相差不足 12%，可见连“最像节点”的那个基因也只是高峰的峰顶。本文交付的是一条判别口径：把“哪个基因重要”换成"
     "“重要在何处、在哪一档证据上成立”，并为两个节点排出各自合适的验证路径——SERPINE1 走前瞻蛋白队列，"
     "TMSB4X 走条件性敲除实验。")

